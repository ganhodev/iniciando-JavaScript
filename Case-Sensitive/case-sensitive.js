/*
Quando uma linguagem de programação é case-sensitive significa que ela diferencia letras maiúsculas de minúsculas. Ou seja, variáveis,
funções e outros identificadores com nomes semelhantes, mas com diferenças de maiúsculas e minúsculas,
 são tratados como entidades distintas.
*/

var product = "Laptop";
var Product = "Smartphone";

console.log(product); // "Laptop"
console.log(Product); // "Smartphone"
//Diferença no primeiro caractere das variáveis, 
// resultando em valores diferentes.