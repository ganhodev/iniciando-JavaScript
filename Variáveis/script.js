//Na programação, uma variável é um espaço na memória do computador que armazena dados temporariamente. Ela pode ser usada para guardar valores que podem mudar durante a execução do programa. As variáveis são essenciais para a manipulação de dados e para a criação de programas dinâmicos.

// Declarar uma variável sem valor.
var user 
console.log(user); // undefined

// Declarar uma variável com valor.
var user = "Guilherme";
console.log(user); // "Alice"

// Substituir o valor da variável.
user = "João";
console.log(user); // "João" 

